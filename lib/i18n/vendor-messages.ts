export function vendorT(key: VendorMessageKey, locale: VendorLocale): string {
  return vendorMessages[locale][key] ?? vendorMessages.en[key];
}

export function translateNavLabel(label: string, locale: VendorLocale): string {
  const key = navLabelMap[label];
  return key ? vendorT(key, locale) : label;
}

export function translateQuickActionLabel(label: string, locale: VendorLocale): string {
  const key = quickActionMap[label];
  return key ? vendorT(key, locale) : label;
}

export function dashboardTitleKeyForRole(role: string): VendorMessageKey {
  if (role === "vendor_admin") return "dashboard.title.admin";
  if (role === "vendor_supervisor") return "dashboard.title.supervisor";
  if (role === "vendor_field_lead") return "dashboard.title.fieldLead";
  return "dashboard.title.worker";
}
